const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync('app/page.tsx', 'utf8');
const start = source.indexOf('function normalizeUpbRole(');
const end = source.indexOf('export default function HomePage');
assert(start >= 0 && end > start);
const context = {};
vm.createContext(context);
vm.runInContext(ts.transpile(source.slice(start, end)), context);
const base = {tournament: {}, userId: 'member', upbRole: 'student', upbCenter: 'BUC', upbFaculty: 'FIIR', upbPartnerName: null, isAdmin: false};
const eligible = (patch) => context.getUpbEligibility({...base, ...patch}).eligible;
for (const role of ['student', 'employee', 'alumni']) assert.equal(eligible({upbRole: role}), true, role);
for (const role of ['guest', null, '', 'unknown']) assert.equal(eligible({upbRole: role}), false, String(role));
assert.equal(eligible({upbFaculty: '  '}), false);
assert.equal(eligible({upbCenter: null}), false);
assert.equal(eligible({upbRole: 'partner', upbCenter: null, upbFaculty: null, upbPartnerName: 'Company'}), true);
assert.equal(eligible({upbRole: 'partner', upbPartnerName: '  '}), false);
assert.equal(eligible({isAdmin: true, upbRole: null, upbCenter: null, upbFaculty: null}), true);
assert.equal(eligible({tournament: {is_upb_championship: true}, upbRole: 'alumni'}), false);
assert.equal(eligible({tournament: {is_upb_championship: true}}), true);
console.log('PASS: 14 self-registration eligibility cases');
